#!/usr/bin/env bash
# Regenerates src/lib/apple-signed-data.fixtures.ts: a throwaway certificate
# chain shaped like the one the App Store signs with (PRD §6.13 B4, S3), for
# the tests of src/lib/apple-signed-data.server.ts. Production code never
# trusts it; it trusts only the pinned Apple Root CA - G3.
#
#   root (P-384, CA) → intermediate (P-384, CA, Apple WWDR marker)
#                    → leaf (P-256, App Store receipt-signer marker)
#
# plus the negative cases: a "developer" leaf without the signer marker, a
# non-CA intermediate and a leaf under it, and an expired leaf.
#
# Usage: scripts/gen-apple-test-chain.sh   (needs OpenSSL 3 and python3)
set -euo pipefail

OUT="$(cd "$(dirname "$0")/.." && pwd)/src/lib/apple-signed-data.fixtures.ts"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cd "$WORK"

cat > ext.cnf <<'EOF'
[req]
distinguished_name = dn
[dn]
[root]
basicConstraints=critical,CA:TRUE
keyUsage=critical,keyCertSign,cRLSign
subjectKeyIdentifier=hash
[inter]
basicConstraints=critical,CA:TRUE,pathlen:0
keyUsage=critical,keyCertSign,cRLSign
1.2.840.113635.100.6.2.1=DER:05:00
[leaf]
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature
1.2.840.113635.100.6.11.1=DER:05:00
[devleaf]
basicConstraints=critical,CA:FALSE
keyUsage=critical,digitalSignature
1.2.840.113635.100.6.1.4=DER:05:00
[noncainter]
basicConstraints=critical,CA:FALSE
1.2.840.113635.100.6.2.1=DER:05:00
EOF

openssl ecparam -name secp384r1 -genkey -noout -out root.key
openssl req -x509 -new -key root.key -sha384 -days 9000 -set_serial 1 \
  -subj "/CN=Gradus Test Root CA/O=Gradus Test" -config ext.cnf -extensions root -out root.pem
openssl ecparam -name secp384r1 -genkey -noout -out inter.key
openssl req -new -key inter.key -subj "/CN=Gradus Test WWDR G6/O=Gradus Test" -config ext.cnf -out inter.csr
openssl x509 -req -in inter.csr -CA root.pem -CAkey root.key -set_serial 2 -days 8000 -sha384 \
  -extfile ext.cnf -extensions inter -out inter.pem
openssl x509 -req -in inter.csr -CA root.pem -CAkey root.key -set_serial 5 -days 8000 -sha384 \
  -extfile ext.cnf -extensions noncainter -out noncainter.pem
openssl ecparam -name prime256v1 -genkey -noout -out leaf.key
openssl req -new -key leaf.key -subj "/CN=Gradus Test App Store Signer/O=Gradus Test" -config ext.cnf -out leaf.csr
openssl x509 -req -in leaf.csr -CA inter.pem -CAkey inter.key -set_serial 3 -days 7000 -sha384 \
  -extfile ext.cnf -extensions leaf -out leaf.pem
openssl x509 -req -in leaf.csr -CA inter.pem -CAkey inter.key -set_serial 4 -days 7000 -sha384 \
  -extfile ext.cnf -extensions devleaf -out devleaf.pem
openssl x509 -req -in leaf.csr -CA noncainter.pem -CAkey inter.key -set_serial 6 -days 7000 -sha384 \
  -extfile ext.cnf -extensions leaf -out leaf_noncainter.pem
openssl x509 -req -in leaf.csr -CA inter.pem -CAkey inter.key -set_serial 7 -sha384 \
  -extfile ext.cnf -extensions leaf -not_before 20200101000000Z -not_after 20200601000000Z \
  -out leaf_expired.pem
openssl verify -CAfile root.pem -untrusted inter.pem leaf.pem >/dev/null

for c in root inter noncainter leaf devleaf leaf_noncainter leaf_expired; do
  openssl x509 -in "$c.pem" -outform der -out "$c.der"
done
openssl ec -in leaf.key -text -noout 2>/dev/null > leafkey.txt

python3 - "$OUT" <<'EOF'
import base64, re, sys
t = open("leafkey.txt").read()
def block(name):
    m = re.search(name + r":\s*\n((?:\s+[0-9a-f:]+\n)+)", t)
    return bytes.fromhex(re.sub(r"[\s:]", "", m.group(1)))
priv, pub = block("priv"), block("pub")
priv = priv[-32:].rjust(32, b"\0")
assert pub[0] == 4 and len(pub) == 65
b64u = lambda x: base64.urlsafe_b64encode(x).decode().rstrip("=")
out = [
    "// Generated by scripts/gen-apple-test-chain.sh — a throwaway test chain shaped like",
    "// Apple's (P-384 root, P-384 WWDR-style intermediate, P-256 signing leaf). Never trusted",
    "// outside tests: production code only trusts the pinned Apple Root CA - G3.",
    "",
    "export const TEST_LEAF_JWK = {",
    '  kty: "EC",',
    '  crv: "P-256",',
    f'  x: "{b64u(pub[1:33])}",',
    f'  y: "{b64u(pub[33:])}",',
    f'  d: "{b64u(priv)}",',
    "} as const;",
    "",
]
names = {"root": "ROOT", "inter": "INTERMEDIATE", "noncainter": "NON_CA_INTERMEDIATE", "leaf": "LEAF",
         "devleaf": "DEVELOPER_LEAF", "leaf_noncainter": "LEAF_UNDER_NON_CA", "leaf_expired": "EXPIRED_LEAF"}
for f, n in names.items():
    d = base64.b64encode(open(f + ".der", "rb").read()).decode()
    chunks = [d[i:i + 88] for i in range(0, len(d), 88)]
    out.append(f"export const TEST_{n}_B64 =")
    out.append("  " + " +\n  ".join(f'"{c}"' for c in chunks) + ";")
    out.append("")
open(sys.argv[1], "w").write("\n".join(out))
EOF
cd - >/dev/null
npx prettier --write "$OUT" >/dev/null
echo "wrote $OUT"
